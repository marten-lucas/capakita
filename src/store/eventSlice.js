const DEFAULT_AUTO_EVENT_SETTINGS = {
    kita: {
        ageYears: 3,
        bookingDeltaHours: 0,
    },
    school: {
        ageYears: 6,
        bookingDeltaHours: 0,
    },
};

function normalizeAutoEventSettings(settings = {}) {
    return {
        kita: {
            ageYears: Number.isFinite(Number(settings?.kita?.ageYears)) ? Number(settings.kita.ageYears) : DEFAULT_AUTO_EVENT_SETTINGS.kita.ageYears,
            bookingDeltaHours: Number.isFinite(Number(settings?.kita?.bookingDeltaHours)) ? Number(settings.kita.bookingDeltaHours) : DEFAULT_AUTO_EVENT_SETTINGS.kita.bookingDeltaHours,
        },
        school: {
            ageYears: Number.isFinite(Number(settings?.school?.ageYears)) ? Number(settings.school.ageYears) : DEFAULT_AUTO_EVENT_SETTINGS.school.ageYears,
            bookingDeltaHours: Number.isFinite(Number(settings?.school?.bookingDeltaHours)) ? Number(settings.school.bookingDeltaHours) : DEFAULT_AUTO_EVENT_SETTINGS.school.bookingDeltaHours,
        },
    };
}

function getScenarioAutoEventSettings(simScenario, scenarioId) {
    const scenario = (simScenario?.scenarios || []).find((entry) => String(entry.id) === String(scenarioId));
    return normalizeAutoEventSettings(scenario?.autoEventSettings);
}

function getNextCalendarDay(dateStr) {
    const date = parseIsoDateUtc(dateStr);
    if (!date) return null;
    date.setUTCDate(date.getUTCDate() + 1);
    return toIsoDateUtc(date);
}

function addYearsToIsoDate(dateStr, years) {
    if (!dateStr) return null;
    const match = String(dateStr).match(/^(\d{4})-(\d{2})-(\d{2})$/);
    if (!match) return null;

    const y = Number(match[1]);
    const m = Number(match[2]) - 1;
    const day = Number(match[3]);
    const d = new Date(Date.UTC(y, m, day));
    if (isNaN(d.getTime())) return null;

    const monthsToAdd = Math.round(Number(years) * 12);
    d.setUTCMonth(d.getUTCMonth() + monthsToAdd);
    return d.toISOString().slice(0, 10);
}

function parseIsoDateUtc(dateStr) {
    if (!dateStr) return null;
    const match = String(dateStr).match(/^(\d{4})-(\d{2})-(\d{2})$/);
    if (!match) return null;

    const year = Number(match[1]);
    const month = Number(match[2]) - 1;
    const day = Number(match[3]);
    const date = new Date(Date.UTC(year, month, day));
    if (isNaN(date.getTime()) || date.getUTCFullYear() !== year || date.getUTCMonth() !== month || date.getUTCDate() !== day) return null;
    return date;
}

function toIsoDateUtc(date) {
    return date.toISOString().slice(0, 10);
}

function isCorridorDeferred(item = {}) {
    const candidates = [
        item?.corridorDeferred,
        item?.schoolEntryDeferred,
        item?.postponeSchoolStart,
    ];

    return candidates.some((value) => value === true);
}

function calculateSchoolEntryDateBavaria(dateOfBirth, deferredInCorridor = false) {
    const birthDate = parseIsoDateUtc(dateOfBirth);
    if (!birthDate) return null;

    const sixthBirthday = new Date(Date.UTC(
        birthDate.getUTCFullYear() + 6,
        birthDate.getUTCMonth(),
        birthDate.getUTCDate()
    ));

    const year = sixthBirthday.getUTCFullYear();
    const month = sixthBirthday.getUTCMonth() + 1;
    const day = sixthBirthday.getUTCDate();

    const isBeforeOrOnJune30 = month < 7 || (month === 6 && day <= 30);
    const isCorridor = (month === 7) || (month === 8) || (month === 9 && day <= 30);
    const enrollmentYear = isBeforeOrOnJune30
        ? year
        : isCorridor
            ? (deferredInCorridor ? year + 1 : year)
            : year + 1;

    // In the simulator, school transition is applied at September start.
    return `${String(enrollmentYear).padStart(4, '0')}-09-01`;
}

function isSchoolTransitionAtAttendanceBoundary(item, transition) {
    if (transition?.targetStage !== 'school' || !item?.enddate || !transition?.effectiveDate) return false;
    const attendanceEnd = parseIsoDateUtc(item.enddate);
    if (!attendanceEnd) return false;
    attendanceEnd.setUTCDate(attendanceEnd.getUTCDate() + 1);
    return toIsoDateUtc(attendanceEnd) === String(transition.effectiveDate);
}

function hasConflictingRealEvent({ existingEvents = [], itemKey, effectiveDate, attendanceEndDate = null, allowSchoolBoundary = false }) {
    return existingEvents.some((event) => {
        if (event?.entityId !== itemKey || event?.effectiveDate !== effectiveDate) return false;
        if (event?.metadata?.autoGenerated) return false;
        if (
            allowSchoolBoundary
            && String(event?.sourceDate || '') === String(attendanceEndDate || '')
            && (event?.type === 'presence_end' || event?.type === 'group_assignment_end')
        ) return false;

        return event?.type === 'group_assignment_start' || event?.type === 'presence_end';
    });
}

function isWithinAttendanceRange(item, effectiveDate) {
    if (!effectiveDate) return false;
    if (item?.startdate && effectiveDate < item.startdate) return false;
    if (item?.enddate && effectiveDate > item.enddate) return false;
    return true;
}

function buildAutomaticTransitionEvents({ dataItems, existingEvents = [], scenarioId, disabledIds = {}, autoEventSettings }) {
    const events = [];
    const settings = normalizeAutoEventSettings(autoEventSettings);
    const realEventsByEntity = new Map();
    for (const event of existingEvents) {
        if (event.type !== 'group_assignment_start' && event.type !== 'presence_end') continue;
        if (!realEventsByEntity.has(event.entityId)) realEventsByEntity.set(event.entityId, []);
        realEventsByEntity.get(event.entityId).push(event);
    }

    Object.entries(dataItems).forEach(([itemKey, item]) => {
        if (item?.type !== 'demand' || !item?.dateofbirth) return;

        const transitions = [
            {
                id: `auto_transition_kita_${itemKey}`,
                effectiveDate: addYearsToIsoDate(item.dateofbirth, settings.kita.ageYears),
                description: 'Automatischer Gruppenwechsel: Krippe → Kita',
                targetStage: 'kita',
                bookingDeltaHours: settings.kita.bookingDeltaHours,
            },
            {
                id: `auto_transition_school_${itemKey}`,
                effectiveDate: calculateSchoolEntryDateBavaria(item.dateofbirth, isCorridorDeferred(item)),
                description: 'Einschulung angenommen: anschließende Betreuung ungeklärt',
                targetStage: 'school',
                bookingDeltaHours: settings.school.bookingDeltaHours,
            }
        ];

        if (item?.enddate) {
            transitions.push({
                id: `auto_transition_exit_${itemKey}`,
                effectiveDate: getNextCalendarDay(item.enddate),
                sourceDate: item.enddate,
                description: 'Austritt nach dem letzten Betreuungstag',
                targetStage: 'exit',
                bookingDeltaHours: 0,
            });
        }

        transitions.forEach((transition) => {
            if (!transition.effectiveDate) return;
            const allowSchoolBoundary = isSchoolTransitionAtAttendanceBoundary(item, transition);
            if (!isWithinAttendanceRange(item, transition.effectiveDate) && !allowSchoolBoundary && transition.targetStage !== 'exit') return;
            if (transition.targetStage !== 'exit' && hasConflictingRealEvent({
                existingEvents: realEventsByEntity.get(itemKey) || [],
                itemKey,
                effectiveDate: transition.effectiveDate,
                attendanceEndDate: item?.enddate,
                allowSchoolBoundary,
            })) return;

            events.push({
                id: transition.id,
                scenarioId,
                effectiveDate: transition.effectiveDate,
                sourceDate: transition.sourceDate || transition.effectiveDate,
                type: 'auto_group_transition',
                category: 'auto_transition',
                entityType: 'demand',
                entityId: itemKey,
                entityName: item.name,
                relatedId: null,
                description: transition.description,
                metadata: {
                    autoGenerated: true,
                    targetStage: transition.targetStage,
                    bookingDeltaHours: transition.bookingDeltaHours,
                },
                enabled: !disabledIds[transition.id]
            });
        });
    });

    return events;
}

function resolveEntityName(dataItems, itemId, explicitName) {
    const valueFromArg = String(explicitName || '').trim();
    if (valueFromArg) return valueFromArg;

    const item = dataItems?.[itemId] || {};
    const firstName = String(item.firstName || '').trim();
    const name = String(item.name || '').trim();

    if (firstName && name) return `${firstName} ${name}`;
    if (name) return name;
    if (firstName) return firstName;

    return 'Unbekannt';
}

// Resolve only the overlay data used by events, avoiding qualification and definition work.
function getEventData(state, scenarioId) {
    const scenarios = state.simScenario?.scenarios || [];
    const byId = new Map(scenarios.map(scenario => [scenario.id, scenario]));
    const chain = [];
    const seen = new Set();
    let currentId = scenarioId;
    while (currentId) {
        if (seen.has(currentId)) throw new Error(`Ereignisse für Szenario ${scenarioId}: Zyklus in der Szenariovererbung bei ${currentId}.`);
        seen.add(currentId);
        const scenario = byId.get(currentId);
        if (!scenario) throw new Error(`Ereignisse für Szenario ${scenarioId}: Basisszenario ${currentId} nicht gefunden.`);
        chain.push(scenario);
        currentId = scenario.baseScenarioId;
    }
    const overlays = state.simOverlay?.overlaysByScenario || {};
    const dataItems = getEffectiveDataItems(chain, overlays, state.simData?.dataByScenario || {});
    const bookingsByItem = {};
    const groupsByItem = {};
    const rawBookings = state.simBooking?.bookingsByScenario || {};
    const rawGroups = state.simGroup?.groupsByScenario || {};
    let forecastInputsDiffer = false;
    for (const itemId of Object.keys(dataItems)) {
        bookingsByItem[itemId] = getEffectiveBookings(chain, overlays, rawBookings, itemId);
        groupsByItem[itemId] = getEffectiveGroupAssignments(chain, overlays, rawGroups, itemId);
        // Forecast's useOverlayData currently selects a whole map from the first
        // matching layer, unlike the chart's per-record merge used above.
        const firstBookings = chain.map(({ id }) => overlays[id]?.bookings?.[itemId] || rawBookings[id]?.[itemId]).find(Boolean) || {};
        const firstGroups = chain.map(({ id }) => overlays[id]?.groupassignments?.[itemId] || rawGroups[id]?.[itemId]).find(Boolean) || {};
        if (Object.keys(firstBookings).length !== Object.keys(bookingsByItem[itemId]).length ||
            Object.keys(firstGroups).length !== Object.keys(groupsByItem[itemId]).length) forecastInputsDiffer = true;
    }
    const rawDefs = state.simGroup?.groupDefsByScenario || {};
    const mergedDefs = getEffectiveGroupDefs(chain, overlays, rawDefs);
    const firstDefs = chain.flatMap(({ id }) => [overlays[id]?.groupDefs, rawDefs[id]])
        .find(defs => Array.isArray(defs) && defs.length > 0) || [];
    const firstDefIds = new Set(firstDefs.map(def => def.id));
    if (firstDefIds.size !== firstDefs.length || firstDefIds.size !== mergedDefs.length) forecastInputsDiffer = true;
    return { dataItems, bookingsByItem, groupsByItem, forecastInputsDiffer };
}

// Extract events for a scenario from state
function extractEventsForScenario(state, scenarioId, disabledIds = {}) {
    const events = [];
    const { dataItems, bookingsByItem, groupsByItem, forecastInputsDiffer } = getEventData(state, scenarioId);
    const autoEventSettings = getScenarioAutoEventSettings(state.simScenario, scenarioId);

    // Helper: create event object
    function createEvent({
        id,
        effectiveDate,
        sourceDate,
        type,
        category,
        entityType,
        entityId,
        entityName,
        relatedId = null,
        description,
        metadata = {},
        enabled = true
    }) {
        return {
            id,
            scenarioId,
            effectiveDate,
            sourceDate,
            type,
            category,
            entityType,
            entityId,
            entityName,
            relatedId,
            description,
            metadata,
            enabled: !disabledIds[id] && enabled
        };
    }

    // Data items: presence (start/end), absences
    Object.entries(dataItems).forEach(([itemKey, item]) => {
        const entityType = item.type === 'capacity' ? 'capacity' : 'demand';
        const entityName = item.name;

        if (item.startdate) {
            events.push(
                createEvent({
                    id: `presence_start_${itemKey}`,
                    effectiveDate: item.startdate,
                    sourceDate: item.startdate,
                    type: 'presence_start',
                    category: 'presence',
                    entityType,
                    entityId: itemKey,
                    entityName,
                    description: `${entityName} beginnt Anwesenheit`
                })
            );
        }
        if (item.enddate) {
            const nextDay = getNextCalendarDay(item.enddate);
            if (nextDay) {
                events.push(
                    createEvent({
                        id: `presence_end_${itemKey}`,
                        effectiveDate: nextDay,
                        sourceDate: item.enddate,
                        type: 'presence_end',
                        category: 'presence',
                        entityType,
                        entityId: itemKey,
                        entityName,
                        description: `${entityName} endet Anwesenheit`
                    })
                );
            }
        }
        // Absences
        (item.absences || []).forEach((abs, absIndex) => {
            const absenceId = abs.id || `absence_${absIndex}`;
            const { start: startDate, end: endDate } = getAbsenceRange(abs);
            if (startDate) {
                events.push(
                    createEvent({
                        id: `absence_start_${itemKey}_${absenceId}`,
                        effectiveDate: startDate,
                        sourceDate: startDate,
                        type: 'absence_start',
                        category: 'absence',
                        entityType,
                        entityId: itemKey,
                        entityName,
                        relatedId: absenceId,
                        description: `${entityName} Abwesenheit beginnt`
                    })
                );
            }
            if (endDate) {
                const nextDay = getNextCalendarDay(endDate);
                if (nextDay) {
                    events.push(
                        createEvent({
                            id: `absence_end_${itemKey}_${absenceId}`,
                            effectiveDate: nextDay,
                            sourceDate: endDate,
                            type: 'absence_end',
                            category: 'absence',
                            entityType,
                            entityId: itemKey,
                            entityName,
                            relatedId: absenceId,
                            description: `${entityName} Abwesenheit endet`
                        })
                    );
                }
            }
        });
    });

    // Bookings: start/end
    Object.entries(bookingsByItem).forEach(([itemId, bookings]) => {
        if (!dataItems?.[itemId]) return;
        Object.values(bookings).forEach(booking => {
            const bookingEntityType = dataItems?.[itemId]?.type === 'capacity' ? 'capacity' : 'demand';
            const bookingEntityName = resolveEntityName(dataItems, itemId, booking.name);
            if (booking.startdate) {
                events.push(
                    createEvent({
                        id: `booking_start_${itemId}_${booking.id}`,
                        effectiveDate: booking.startdate,
                        sourceDate: booking.startdate,
                        type: 'booking_start',
                        category: 'booking',
                        entityType: bookingEntityType,
                        entityId: itemId,
                        entityName: bookingEntityName,
                        relatedId: booking.id,
                        description: `Buchung beginnt (${booking.id})`,
                        metadata: { bookingTimes: booking.times || [] }
                    })
                );
            }
            if (booking.enddate) {
                const nextDay = getNextCalendarDay(booking.enddate);
                if (nextDay) {
                    events.push(
                        createEvent({
                            id: `booking_end_${itemId}_${booking.id}`,
                            effectiveDate: nextDay,
                            sourceDate: booking.enddate,
                            type: 'booking_end',
                            category: 'booking',
                            entityType: bookingEntityType,
                            entityId: itemId,
                            entityName: bookingEntityName,
                            relatedId: booking.id,
                            description: `Buchung endet (${booking.id})`,
                            metadata: { bookingTimes: booking.times || [] }
                        })
                    );
                }
            }
        });
    });

    // Group assignments: start/end
    Object.entries(groupsByItem).forEach(([itemId, assignments]) => {
        if (!dataItems?.[itemId]) return;
        Object.values(assignments).forEach(assignment => {
            const groupEntityType = dataItems?.[itemId]?.type === 'capacity' ? 'capacity' : 'demand';
            const assignmentEntityName = resolveEntityName(dataItems, itemId, assignment.name);
            if (assignment.start) {
                events.push(
                    createEvent({
                        id: `group_assignment_start_${itemId}_${assignment.id}`,
                        effectiveDate: assignment.start,
                        sourceDate: assignment.start,
                        type: 'group_assignment_start',
                        category: 'group_assignment',
                        entityType: groupEntityType,
                        entityId: itemId,
                        entityName: assignmentEntityName,
                        relatedId: assignment.id,
                        description: `Gruppenzuweisung beginnt (${assignment.groupId})`,
                        metadata: { groupId: assignment.groupId, groupName: assignment.groupName }
                    })
                );
            }
            if (assignment.end) {
                const nextDay = getNextCalendarDay(assignment.end);
                if (nextDay) {
                    events.push(
                        createEvent({
                            id: `group_assignment_end_${itemId}_${assignment.id}`,
                            effectiveDate: nextDay,
                            sourceDate: assignment.end,
                            type: 'group_assignment_end',
                            category: 'group_assignment',
                            entityType: groupEntityType,
                            entityId: itemId,
                            entityName: assignmentEntityName,
                            relatedId: assignment.id,
                            description: `Gruppenzuweisung endet (${assignment.groupId})`,
                            metadata: { groupId: assignment.groupId, groupName: assignment.groupName }
                        })
                    );
                }
            }
        });
    });

    events.push(...buildAutomaticTransitionEvents({ dataItems, existingEvents: events, scenarioId, disabledIds, autoEventSettings }));

    // Post-process: add simulatedDate field.
    // Rule (Option A): for each entity, if there are events on day T and day T+1, the T-events get simulatedDate = T+1.
    // All others: simulatedDate = effectiveDate (same as actualDate).
    const eventsByEntityAndDate = new Map();
    events.forEach((event) => {
        const key = String(event.entityId || '');
        if (!key) return;
        if (!eventsByEntityAndDate.has(key)) eventsByEntityAndDate.set(key, new Set());
        eventsByEntityAndDate.get(key).add(String(event.effectiveDate || ''));
    });

    events.forEach((event) => {
        const entityId = String(event.entityId || '');
        const effectiveDate = String(event.effectiveDate || '');
        // actualDate is the unmodified effectiveDate
        event.actualDate = effectiveDate;

        if (!entityId || !effectiveDate) {
            event.simulatedDate = effectiveDate;
            return;
        }

        const dateObj = parseIsoDateUtc(effectiveDate);
        if (!dateObj) {
            event.simulatedDate = effectiveDate;
            return;
        }

        const nextDayObj = new Date(dateObj.getTime());
        nextDayObj.setUTCDate(nextDayObj.getUTCDate() + 1);
        const nextDayIso = toIsoDateUtc(nextDayObj);

        const entityDates = eventsByEntityAndDate.get(entityId);
        if (entityDates && entityDates.has(nextDayIso)) {
            event.simulatedDate = nextDayIso;
        } else {
            event.simulatedDate = effectiveDate;
        }
    });

    return { events, forecastInputsDiffer };
}

function refreshScenario(state, source, scenarioId) {
    if (!state.statusByScenario) state.statusByScenario = {};
    try {
        const result = extractEventsForScenario(source, scenarioId, state.disabledEventIdsByScenario[scenarioId] || {});
        state.eventsByScenario[scenarioId] = result.events;
        state.statusByScenario[scenarioId] = result.forecastInputsDiffer
            ? { state: 'incomplete', error: `Abweichende Overlay-Auflösung für Buchungen, Gruppen oder Gruppendefinitionen im Szenario ${scenarioId}. Prognose unvollständig.` }
            : { state: 'ready', error: null };
    } catch (error) {
        delete state.eventsByScenario[scenarioId];
        state.statusByScenario[scenarioId] = { state: 'error', error: error instanceof Error ? error.message : String(error) };
    }
}

const eventSlice = createSlice({
    name: 'events',
    initialState: {
        eventsByScenario: {},
        disabledEventIdsByScenario: {},
        statusByScenario: {},
        _needsRefresh: false,
    },
    reducers: {
        // Manual trigger to refresh events for all scenarios
        refreshAllEvents(state, action) {
            const { simScenario } = action.payload;
            state.eventsByScenario = {};
            state.statusByScenario = {};
            (simScenario?.scenarios || []).forEach(({ id: scenarioId }) => {
                refreshScenario(state, action.payload, scenarioId);
            });
            state._needsRefresh = false;
            state._refreshBlocked = false;
            state._refreshError = null;
        },
        // Manual trigger for one scenario
        refreshEventsForScenario(state, action) {
            const { scenarioId } = action.payload;
            refreshScenario(state, action.payload, scenarioId);
            // A single scenario cannot make an invalidated global cache complete.
        },
        invalidateEvents(state) {
            state.eventsByScenario = {};
            state.statusByScenario = {};
            state._needsRefresh = true;
            state._refreshBlocked = false;
            state._refreshError = null;
        },
        eventRefreshFailed(state, action) {
            state.eventsByScenario = {};
            state.statusByScenario = {};
            state._needsRefresh = true;
            state._refreshBlocked = true;
            state._refreshError = action.payload;
        },
        setEventEnabled(state, action) {
            const { scenarioId, eventId, enabled } = action.payload;
            if (!state.disabledEventIdsByScenario[scenarioId]) {
                state.disabledEventIdsByScenario[scenarioId] = {};
            }

            if (enabled) {
                delete state.disabledEventIdsByScenario[scenarioId][eventId];
            } else {
                state.disabledEventIdsByScenario[scenarioId][eventId] = true;
            }

            const events = state.eventsByScenario[scenarioId];
            if (events) {
                state.eventsByScenario[scenarioId] = events.map((event) =>
                    event.id === eventId ? { ...event, enabled } : event
                );
            }
        },
        clearEventOverridesForScenario(state, action) {
            const { scenarioId } = action.payload;
            delete state.disabledEventIdsByScenario[scenarioId];
            delete state.eventsByScenario[scenarioId];
            if (state.statusByScenario) delete state.statusByScenario[scenarioId];
            state._needsRefresh = true;
            state._refreshBlocked = false;
            state._refreshError = null;
        },
    },
    extraReducers: (builder) => {
        // Listen to relevant actions and mark for refresh
        builder.addMatcher(
            (action) =>
                action.type.startsWith('simData/') ||
                action.type.startsWith('simBooking/') ||
                action.type.startsWith('simGroup/') ||
                action.type.startsWith('simOverlay/') ||
                ['simScenario/addScenario', 'simScenario/updateScenario', 'simScenario/deleteScenario', 'simScenario/setScenarios'].includes(action.type),
            (state) => {
                state.eventsByScenario = {};
                state.statusByScenario = {};
                state._needsRefresh = true;
                state._refreshBlocked = false;
                state._refreshError = null;
            }
        );
    },
});

// Older snapshots do not have per-scenario statuses; retain their global freshness semantics.
export const selectForecastEventsAvailable = (state, scenarioId) => {
    const events = state.events;
    if (!scenarioId || !Array.isArray(events?.eventsByScenario?.[scenarioId])) return false;
    const status = events?.statusByScenario?.[scenarioId];
    return status ? status.state === 'ready' : !events?._needsRefresh && !events?._refreshBlocked;
};

export const selectForecastEventsError = (state, scenarioId) =>
    state.events?.statusByScenario?.[scenarioId]?.error || state.events?._refreshError || null;

// Selector: get all events for a scenario
export const selectEventsForScenario = createSelector(
  [
    (state, scenarioId) => state.events?.eventsByScenario?.[scenarioId]
  ],
  (events) => {
    return events ? [...events] : []; // Transform: create new array
  }
);

// Selector: get consolidated events by effectiveDate (future only)
export const selectConsolidatedEventsForScenario = createSelector(
  [selectEventsForScenario],
  (events) => {
    if (!events || events.length === 0) return [];
    const today = new Date().toISOString().slice(0, 10);
    // Helper: is event ongoing (started in past, no end event)
    function isOngoing(ev) {
        // Only applies to group_assignment_start, child_presence_start, employee_presence_start, booking_start
        if (
            ev.type === 'group_assignment_start' ||
            ev.type === 'child_presence_start' ||
            ev.type === 'employee_presence_start' ||
            ev.type === 'booking_start'
        ) {
            // Find corresponding end event for this item
            const endType =
                ev.type === 'group_assignment_start' ? 'group_assignment_end'
                    : ev.type === 'child_presence_start' ? 'child_presence_end'
                        : ev.type === 'employee_presence_start' ? 'employee_presence_end'
                            : ev.type === 'booking_start' ? 'booking_end'
                                : null;
            if (!endType) return false;
            // Find end event for this item
            const hasEnd = events.some(e =>
                e.type === endType &&
                e.itemId === ev.itemId &&
                (e.groupId ? e.groupId === ev.groupId : true) &&
                (e.bookingId ? e.bookingId === ev.bookingId : true) &&
                (e.assignmentId ? e.assignmentId === ev.assignmentId : true) &&
                e.effectiveDate >= today
            );
            // If no end event in the future, and start is in the past, it's ongoing
            return !hasEnd && ev.effectiveDate <= today;
        }
        return false;
    }

    // Filter: future events or ongoing events
    const filteredEvents = events.filter(ev =>
      ev.enabled !== false && (ev.effectiveDate >= today || isOngoing(ev))
    );

    const byDate = {};
    filteredEvents.forEach(ev => {
      if (!byDate[ev.effectiveDate]) byDate[ev.effectiveDate] = [];
      byDate[ev.effectiveDate].push(ev);
    });
    return Object.entries(byDate)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([date, events]) => ({ date, events }));
  }
);

export const { refreshAllEvents, refreshEventsForScenario, invalidateEvents, eventRefreshFailed, setEventEnabled, clearEventOverridesForScenario } = eventSlice.actions;
export default eventSlice.reducer;

