function isUnknownEntityName(name) {
  return !name || String(name).trim().toLowerCase() === 'unbekannt';
}

export function filterEventsForDisplay(events = [], {
  mode = 'all',
  nameFilter = '',
  activeChildrenOnly = false,
  activeChildIds = new Set(),
  selectedGroupIds = [],
  currentGroupByChildId = new Map(),
} = {}) {
  const normalizedName = String(nameFilter || '').trim().toLocaleLowerCase('de-DE');
  const selectedGroupSet = new Set((selectedGroupIds || []).map(String));

  return (events || []).filter((event) => {
    if (isUnknownEntityName(event?.entityName)) return false;
    if (mode === 'auto' && !event.metadata?.autoGenerated) return false;
    if (mode === 'real' && event.metadata?.autoGenerated) return false;
    if (normalizedName && !String(event.entityName || '').toLocaleLowerCase('de-DE').includes(normalizedName)) return false;

    if (event.entityType !== 'demand') return true;

    const childId = String(event.entityId || '');
    if (activeChildrenOnly && !activeChildIds.has(childId)) return false;
    if (selectedGroupSet.size > 0) {
      const groupId = String(currentGroupByChildId.get(childId) || '__NO_GROUP__');
      if (!selectedGroupSet.has(groupId)) return false;
    }

    return true;
  });
}
