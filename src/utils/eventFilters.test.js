import { describe, expect, it } from 'vitest';
import { filterEventsForDisplay } from './eventFilters';

const events = [
  { id: 'active-child', entityType: 'demand', entityId: 'child-1', entityName: 'Märta Beispiel', metadata: {} },
  { id: 'inactive-child', entityType: 'demand', entityId: 'child-2', entityName: 'Max Beispiel', metadata: { autoGenerated: true } },
  { id: 'employee', entityType: 'capacity', entityId: 'staff-1', entityName: 'Mara Team', metadata: {} },
  { id: 'unknown', entityType: 'demand', entityId: 'child-3', entityName: 'Unbekannt', metadata: {} },
];

describe('filterEventsForDisplay', () => {
  it('filters active children and current groups while retaining non-child events', () => {
    const filtered = filterEventsForDisplay(events, {
      activeChildrenOnly: true,
      activeChildIds: new Set(['child-1']),
      selectedGroupIds: ['group-1'],
      currentGroupByChildId: new Map([['child-1', 'group-1'], ['child-2', 'group-2']]),
    });

    expect(filtered.map((event) => event.id)).toEqual(['active-child', 'employee']);
  });

  it('filters names without regard to case and preserves automatic/real mode filtering', () => {
    expect(filterEventsForDisplay(events, { nameFilter: 'MÄRTA' }).map((event) => event.id)).toEqual(['active-child']);
    expect(filterEventsForDisplay(events, { mode: 'auto' }).map((event) => event.id)).toEqual(['inactive-child']);
    expect(filterEventsForDisplay(events, { mode: 'real' }).map((event) => event.id)).toEqual(['active-child', 'employee']);
  });

  it('supports filtering the no-group bucket', () => {
    const filtered = filterEventsForDisplay(events, {
      selectedGroupIds: ['__NO_GROUP__'],
      currentGroupByChildId: new Map([['child-1', '__NO_GROUP__']]),
    });

    expect(filtered.map((event) => event.id)).toEqual(['active-child', 'inactive-child', 'employee']);
  });
});
