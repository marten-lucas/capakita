import React from 'react';
import dayjs from 'dayjs';
import { Badge, Divider, Group, Paper, SegmentedControl, Stack, Text } from '@mantine/core';
import { useSelector } from 'react-redux';
import { useScenarioEvents } from '../../hooks/useScenarioEvents';
import { selectPrimarySelectedItemId } from '../../store/simScenarioSlice';

function EventList({ events, emptyText }) {
  if (events.length === 0) {
    return <Text size="sm" c="dimmed">{emptyText}</Text>;
  }

  return (
    <Stack gap="xs">
      {events.map((event) => (
        <Paper key={event.id || `${event.type}-${event.effectiveDate}`} withBorder p="sm" radius="md">
          <Group justify="space-between" align="flex-start" wrap="nowrap">
            <Text size="sm" fw={600}>{event.description || String(event.type || 'Ereignis').replace(/_/g, ' ')}</Text>
            <Text size="xs" c="dimmed" style={{ whiteSpace: 'nowrap' }}>
              {event.effectiveDate ? dayjs(event.effectiveDate).format('DD.MM.YYYY') : 'Ohne Datum'}
            </Text>
          </Group>
          {event.category ? (
            <Badge mt="xs" variant="light" color="gray">{String(event.category).replace(/_/g, ' ')}</Badge>
          ) : null}
        </Paper>
      ))}
    </Stack>
  );
}

export default function SimDataEventsTab() {
  const scenarioId = useSelector((state) => state.simScenario.selectedScenarioId);
  const itemId = useSelector(selectPrimarySelectedItemId);
  const { events } = useScenarioEvents(scenarioId);
  const [eventType, setEventType] = React.useState('real');

  const childEvents = React.useMemo(() => (events || [])
    .filter((event) => String(event.entityId || '') === String(itemId || ''))
    .sort((left, right) => String(left.effectiveDate || '').localeCompare(String(right.effectiveDate || ''))), [events, itemId]);
  const realEvents = childEvents.filter((event) => !event.metadata?.autoGenerated);
  const automaticEvents = childEvents.filter((event) => Boolean(event.metadata?.autoGenerated));

  return (
    <Stack gap="sm" data-testid="simdata-events-tab">
      <Text size="sm" c="dimmed">Ereignisse für dieses Kind. Diese Übersicht ist schreibgeschützt.</Text>
      <SegmentedControl
        value={eventType}
        onChange={(value) => setEventType(value || 'real')}
        data={[
          { label: `Reale (${realEvents.length})`, value: 'real' },
          { label: `Automatische (${automaticEvents.length})`, value: 'auto' },
        ]}
        fullWidth
        data-testid="simdata-events-type-filter"
      />
      <Divider />
      {eventType === 'auto' ? (
        <EventList events={automaticEvents} emptyText="Für dieses Kind sind keine automatischen Ereignisse vorhanden." />
      ) : (
        <EventList events={realEvents} emptyText="Für dieses Kind sind keine realen Ereignisse vorhanden." />
      )}
    </Stack>
  );
}
